    db=pymysql.connect(host="localhost",user="root",password="root",database="my56")
    cur=db.cursor()
    xa=int(ea.get())
    xb=eb.get()
    xc=int(ec.get())
    xd=int(ed.get())
    sql="insert into courses values (%s,%s,%s,%s)"
